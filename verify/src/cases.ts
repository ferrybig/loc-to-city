/**
 * The spot-checks of the worldwide build: the executable half of
 * `countries.md`. Each case is a coordinate, the answer it should have, and
 * where the ledger talks about it (`section`, `entry`, `status`).
 * `evaluate.ts` runs them; `test/world-queries.test.ts` asserts them and
 * `export.ts` writes them out for the demo's map markers.
 *
 * Keep this file and `countries.md` in step: `test/ledger.test.ts` checks
 * that every section exists and that every `entry` is a bullet there whose
 * marker (`*(open)*`, `*(false positive)*`, ...) equals the case's `status`.
 */

/** Any non-empty answer: the tier must resolve, whatever it is called. */
export const ANY = Symbol("any");
/** The tier must resolve to nothing (a place that belongs to no country). */
export const NONE = Symbol("none");
/** The place is named for `namedFor`: it is a whole word of one of the place's names, ignoring case and diacritics. */
export interface NamedFor {
	namedFor: string;
	/** Other spellings or scripts of the same name. */
	aliases?: readonly string[];
}
/** A name the place is known by (local or international), or any of several. */
export type Expected =
	| string
	| readonly string[]
	| typeof ANY
	| typeof NONE
	| NamedFor;

/**
 * What `countries.md` says about the place, by the marker on its entry:
 * - `fixed`: resolves correctly and must keep doing so (an entry without a marker).
 * - `false-positive`: looked wrong on the map, is right. Also must keep resolving.
 * - `open`: wrong today and fixable. The case holds the *expected* answer.
 * - `unsolvable`: wrong today, nothing in this pipeline can fix it.
 * - `human-error`: the source data is wrong; worth reporting upstream.
 */
export type Status =
	| "fixed"
	| "false-positive"
	| "open"
	| "unsolvable"
	| "human-error";

export interface Case {
	/** Shown as the test title and on the map. */
	name: string;
	at: readonly [lat: number, lon: number];
	country?: Expected;
	region?: Expected;
	city?: Expected;
	/** Must resolve to a different city id than this point (two same-named places, not one). */
	otherCityThan?: readonly [lat: number, lon: number];
	status: Status;
	/** The `## ` heading of `countries.md` this belongs to, without its ISO code. */
	section: string;
	/** Start of the bold title of the bullet in that section; required unless `status` is `fixed`. */
	entry?: string;
}

