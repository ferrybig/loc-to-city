// ---- Capitals ----
//
// Every country's (and dependency's) capital: [country, capital, lat, lon,
// aliases?]. The capitals are GeoNames' (cities500.txt, feature code PPLC,
// at the coordinates it gives), each paired with the country name
// hierarchy.json uses for that ISO code. A capital passes when the country
// is right and the *city* that resolved is named for the capital: the
// capital's name (GeoNames' name, its ASCII form, or an alias for another
// spelling or script) is a whole word of one of the city's names, ignoring
// case and diacritics. The point of the tiers is that "all photos in the
// city of Beijing" is a city query, so a capital must not answer with a
// district inside it ("Dongcheng District"), nor only as a region
// ("Berlin" with no city), nor with the country's own name.
//
// Left out: GeoNames lists no capital for Antarctica, Western Sahara,
// Heard I. and McDonald Is., Israel, Br. Indian Ocean Ter., Palestine and
// U.S. Minor Outlying Is. (uninhabited, or contested).
//
// CAPITALS are the ones that resolve today and must keep resolving.
// OPEN_CAPITALS are the ones that do not (measured on world-high-res.bin,
// built 2026-10-12); countries.md's "Capitals." entry says why. Move a row
// up when it starts passing.
export type Capital = readonly [
	country: string,
	capital: string,
	lat: number,
	lon: number,
	aliases?: readonly string[],
];

