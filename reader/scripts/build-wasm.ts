/**
 * Compiles wasm/chunkDecoder.wat into src/chunkDecoderWasm.ts, the
 * module's bytes as a base64 string, so the reader ships it inline and
 * keeps no runtime dependencies (wabt is a devDependency).
 *
 *   npm run build:wasm -w reader
 *
 * test/chunkDecoder.test.ts fails when the committed file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import initWabt from "wabt";

const WAT = fileURLToPath(new URL("../wasm/chunkDecoder.wat", import.meta.url));
const OUT = fileURLToPath(
	new URL("../src/chunkDecoderWasm.ts", import.meta.url),
);

/** The generated module's source for the .wat file's current contents. */
export async function generate(): Promise<string> {
	const wabt = await initWabt();
	const module = wabt.parseWat("chunkDecoder.wat", readFileSync(WAT, "utf8"), {
		simd: true,
	});
	try {
		module.validate();
		const { buffer } = module.toBinary({});
		const base64 = Buffer.from(buffer).toString("base64");
		return `// Generated by \`npm run build:wasm -w reader\` from wasm/chunkDecoder.wat; do not edit.

/** chunkDecoder.wat's compiled module (${buffer.length} bytes), base64. */
export const CHUNK_DECODER_WASM =
	"${base64}";
`;
	} finally {
		module.destroy();
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	writeFileSync(OUT, await generate());
	console.log(`wrote ${OUT}`);
}
