/**
 * Compiles the WebAssembly fast paths in wasm/ into src/, each module's
 * bytes as a base64 string, so the reader ships them inline and keeps no
 * runtime dependencies (wabt is a devDependency):
 * wasm/chunkDecoder.wat into src/chunkDecoderWasm.ts, and
 * wasm/rangeDecoder.wat into src/rangeDecoderWasm.ts.
 *
 *   npm run build:wasm -w reader
 *
 * test/chunkDecoder.test.ts and test/rangeChunk.test.ts fail when a
 * committed file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import initWabt from "wabt";

/** Each module: its .wat source, the generated file, and its export. */
export const MODULES = [
	{
		wat: "chunkDecoder.wat",
		out: "chunkDecoderWasm.ts",
		name: "CHUNK_DECODER_WASM",
	},
	{
		wat: "rangeDecoder.wat",
		out: "rangeDecoderWasm.ts",
		name: "RANGE_DECODER_WASM",
	},
] as const;

const pathOf = (relative: string) =>
	fileURLToPath(new URL(relative, import.meta.url));

/** The generated module's source for a .wat file's current contents
 * (chunkDecoder.wat unless another of `MODULES` is named). */
export async function generate(
	module: (typeof MODULES)[number] = MODULES[0],
): Promise<string> {
	const wabt = await initWabt();
	const parsed = wabt.parseWat(
		module.wat,
		readFileSync(pathOf(`../wasm/${module.wat}`), "utf8"),
		{ simd: true, bulk_memory: true },
	);
	try {
		parsed.validate();
		const { buffer } = parsed.toBinary({});
		const base64 = Buffer.from(buffer).toString("base64");
		return `// Generated by \`npm run build:wasm -w reader\` from wasm/${module.wat}; do not edit.

/** ${module.wat}'s compiled module (${buffer.length} bytes), base64. */
export const ${module.name} =
	"${base64}";
`;
	} finally {
		parsed.destroy();
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	for (const module of MODULES) {
		const out = pathOf(`../src/${module.out}`);
		writeFileSync(out, await generate(module));
		console.log(`wrote ${out}`);
	}
}
